package llm

import (
	"context"
	"encoding/json"
)

// Delta — one fragment of a streaming response.
type Delta struct {
	Text string
}

// Tool description — goes into the "tools" field of the request.
type ToolDef struct {
	Name        string
	Description string
	Parameters  json.RawMessage // JSON Schema of the arguments
}

// A message in the history. Role: "system" | "user" | "assistant" | "tool".
type Message struct {
	Role       string
	Content    string
	ToolCallID string     // for role="tool": links the result to the call
	ToolCalls  []ToolCall // for role="assistant": generated calls
}

// A single tool call generated by the model.
type ToolCall struct {
	ID        string
	Name      string
	Arguments string // JSON string
}

// Client — a neutral provider interface: two methods are enough.
type Client interface {
	Complete(ctx context.Context, req Request) (*Response, error)
	Stream(ctx context.Context, req Request) (Stream, error)
}

// Stream — an iterator over the deltas of a streaming response (used in ch. 20).
type Stream interface {
	Recv() (Delta, error) // Delta{Text string}; at the end — io.EOF
	Close() error
}

// Request — a single request to the model.
type Request struct {
	Model       string
	Messages    []Message
	Tools       []ToolDef
	Temperature float64 // generation quality: 0.0–0.3 for agent loops (ch. 01)
}

// Response — the shape of the real wire protocol: the model's answer in Choices[0].Message.
type Response struct {
	Choices []Choice
	Usage   Usage
}

// Usage — token usage as counted by the provider. The primary source
// of numbers for the budget (ch. 13): PromptTokens is ground truth, your own estimates are the fallback.
type Usage struct {
	PromptTokens     int
	CompletionTokens int
	CacheReadTokens  int // prompt cache hit: > 0 means the prefix came from cache
}

type Choice struct {
	Message      Message
	FinishReason string
}
